import torch

# ── Данные ────────────────────────────────────────────────────────────────────
CROPS_DIR  = "database/meter_ocr_data/cnn_dataset_gold"
OUTPUT_DIR = "meter_ocr/runs/cnn/runs/v2_gold"

IMG_SIZE  = 96  # Целевой размер длинной стороны (для A.LongestMaxSize)
IMG_WIDTH = 48  # Целевая ширина канваса (для A.PadIfNeeded, min_width)
# Почему не квадрат 96x96: типичный кроп цифры имеет aspect ratio (W/H)
# в районе 0.41-0.46 (медиана/P75 по статистике датасета), т.е. после
# LongestMaxSize(96) реальная ширина цифры ~40-44px. Паддинг до квадрата
# 96x96 означал бы больше половины канваса — пустой чёрный фон, что
# бессмысленно тратит разрешение и compute. IMG_WIDTH=48 покрывает с
# небольшим запасом основную массу распределения (до P90-P95 по AR);
# более широкие редкие кропы (AR>1, "широкие и короткие") не обрезаются —
# PadIfNeeded только добавляет паддинг, не режет, — а автоматически
# получают больший канвас, который выравнивается динамическим collate
# в dataset_cnn.py. Если после смены датасета сильно поменяется
# распределение aspect ratio, пересчитайте IMG_WIDTH под P90-P95.

# ── Нормализация ──────────────────────────────────────────────────────────────
# ВАЖНО: это НЕ статистики ImageNet (у ImageNet mean=[0.485,0.456,0.406],
# std=[0.229,0.224,0.225]) — это статистики, посчитанные на собственном
# датасете кропов (значения близки между каналами, т.к. изображения по
# сути grayscale, продублированный в 3 канала). Если поменяется датасет
# или препроцессинг (например, диапазон яркости/инверсия) — пересчитайте.
NORM_MEAN = [0.4618, 0.4503, 0.4438]
NORM_STD  = [0.2871, 0.2865, 0.2913]

# ── Split данных ──────────────────────────────────────────────────────────────
TRAIN_RATIO = 0.7
VAL_RATIO   = 0.15   # test = 1 - TRAIN_RATIO - VAL_RATIO

# ── Обучение ──────────────────────────────────────────────────────────────────
EPOCHS     = 100
BATCH_SIZE = 32
LR         = 1e-3
WEIGHT_DECAY = 1e-4
PATIENCE   = 20          # early stopping: эпох без улучшения val_acc
LABEL_SMOOTHING = 0.1
DROPOUT    = 0.4         # Dropout перед последним Linear-слоем классификатора

NUM_CLASSES = 10
SEED        = 67

# ── Инференс ──────────────────────────────────────────────────────────────────
MIN_CONFIDENCE = 0.8     # порог "хорошего" предсказания в infer_cnn.py

# ── Устройство ────────────────────────────────────────────────────────────────
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")